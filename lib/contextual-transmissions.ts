/**
 * Canton Quests — Contextual Transmission Engine
 * =================================================
 * The central resolver every live-game system calls to decide "should the
 * Commander say something right now, and if so, what?" — replacing a
 * pattern of scattered per-page conditionals (the Commander Videos mission
 * hand-wired 13 of these one at a time) with one reusable rule table and
 * one resolve/show pair of functions.
 *
 * Reuses, never duplicates:
 *   - the real 1-15 Commander video archive (lib/commander-transmissions.ts)
 *     — a rule may reference one of these numbered videos, but ONLY when
 *     that video's actual content genuinely matches the trigger. Most of
 *     the newer trigger names below have no matching video and resolve to
 *     short text (QuestCommanderTransmission type: 'PHOTO_MESSAGE') instead
 *     — never a guessed video assignment.
 *   - the per-quest QuestCommanderTransmission fields already on Quest
 *     (commanderTransmission / completionTransmission / etc, lib/types.ts)
 *     for quest_intro/quest_completion — this engine deliberately does NOT
 *     register a generic default for those two triggers; callers pass the
 *     quest's own authored transmission in as `inlineContent`.
 *   - lib/transmission-viewed-state.ts for de-dupe AND (new) cooldown.
 *   - GameMomentManager (showGameMoment) — the resolved output flows into
 *     the exact same 'commander-transmission' moment that already exists.
 *
 * Server state must cause transmissions; transmissions never create it.
 * Nothing in this file performs a database read or write, awards XP/entries,
 * or mutates any game state — it only ever returns a display payload
 * (QuestCommanderTransmission | undefined) or a boolean "should I show one."
 */

import { CommanderTransmissionTrigger, showGameMoment } from './game-effects';
import { QuestCommanderTransmission, StartingPath } from './types';
import { getTransmissionById, toGameplayTransmission } from './commander-transmissions';
import { isKnownCantonLaunchSlug } from './launch-status';
import { hasViewedTransmission, hasActiveCooldown, markTransmissionViewed } from './transmission-viewed-state';

export interface ContextualTransmissionContext {
  trigger: CommanderTransmissionTrigger;
  eventSlug: string;
  playerId?: string;
  path?: StartingPath;
  questId?: string;
  /** Stable de-dupe/cooldown identity. Defaults to questId, else the trigger name itself. */
  subjectKey?: string;
  /**
   * Ad-hoc content authored outside the static rule table — a GM-authored
   * live-event message, or a quest's own per-quest QuestCommanderTransmission
   * being routed through this engine's de-dupe/cooldown/GameMoment plumbing.
   * When present, this always wins over any registered rule.
   */
  inlineContent?: { headline: string; message: string; cta?: string; posterKey?: string; replayable?: boolean };
  /** Presentational only — see QuestCommanderTransmission.countdownEndsAt. */
  countdownEndsAt?: string;
  /** Server-computed clock. Real callers always pass new Date() (or omit it) — never a client-supplied value. */
  now?: Date;
  /** Test-only: substitute the rule table so window/cooldown/priority behavior can be verified without touching the real registry. Never set by production callers. */
  rulesOverride?: ContextualTransmissionRule[];
}

export interface ContextualTransmissionRule {
  id: string;
  trigger: CommanderTransmissionTrigger;
  /** Only matches this exact starting path when set; undefined = any path / city-wide. */
  pathScope?: StartingPath;
  /** Highest-priority matching rule wins when more than one candidate qualifies. */
  priority: number;
  /** Auto-show at most once ever, per player, per subjectKey. */
  onceParPlayer: boolean;
  /** Whether a manual "replay" control may re-open this after first view. */
  replayable: boolean;
  /** For a repeatable (onceParPlayer: false) trigger, the minimum gap between two auto-shows. */
  cooldownMs?: number;
  startsAt?: string;
  endsAt?: string;
  content: { kind: 'video'; commanderVideoId: number } | { kind: 'text'; headline: string; message: string; cta?: string };
}

