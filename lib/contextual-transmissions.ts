function findMatchingRule(context: ContextualTransmissionContext): ContextualTransmissionRule | undefined {
  const now = context.now ?? new Date();
  const nowMs = now.getTime();
  const candidates = (context.rulesOverride ?? CONTEXTUAL_TRANSMISSION_RULES).filter((rule) => {
    if (rule.trigger !== context.trigger) return false;
    if (rule.pathScope && rule.pathScope !== context.path) return false;
    if (rule.startsAt && new Date(rule.startsAt).getTime() > nowMs) return false;
    if (rule.endsAt && new Date(rule.endsAt).getTime() <= nowMs) return false;
    return true;
  });
  if (candidates.length === 0) return undefined;
  return candidates.sort((a, b) => b.priority - a.priority)[0];
}

function subjectKeyFor(context: ContextualTransmissionContext): string {
  return context.subjectKey || context.questId || context.trigger;
}

/**
 * Pure resolution: given a context, what should the Commander show (if
 * anything)? Never touches storage, GameMomentManager, or any DB — see
 * showContextualTransmission for the version that actually fires it.
 * Always undefined for an event outside Founder's Cipher scope, or when
 * nothing matches.
 */
export function resolveContextualTransmission(context: ContextualTransmissionContext): QuestCommanderTransmission | undefined {
  if (!isKnownCantonLaunchSlug(context.eventSlug)) return undefined;

  if (context.inlineContent) {
    return {
      type: 'PHOTO_MESSAGE',
      headline: context.inlineContent.headline,
      message: context.inlineContent.message,
      posterKey: context.inlineContent.posterKey,
      cta: context.inlineContent.cta || 'CONTINUE',
      replayable: context.inlineContent.replayable ?? true,
      skippable: true,
      countdownEndsAt: context.countdownEndsAt,
    };
  }

  const rule = findMatchingRule(context);
  if (!rule) return undefined;

  if (rule.content.kind === 'video') {
    const entry = getTransmissionById(rule.content.commanderVideoId);
    if (!entry) return undefined;
    return toGameplayTransmission(entry);
  }

  return {
    type: 'PHOTO_MESSAGE',
    headline: rule.content.headline,
    message: rule.content.message,
    cta: rule.content.cta || 'CONTINUE',
    replayable: rule.replayable,
    skippable: true,
    countdownEndsAt: context.countdownEndsAt,
  };
}

/**
 * Whether this context should auto-fire right now — combines event scope,
 * once-per-player de-dupe, and cooldown. gm_announcement/emergency always
 * pass (they intentionally bypass de-dupe, matching the pre-existing rule
 * for gm_announcement — see lib/transmission-viewed-state.ts).
 */
export function shouldShowContextualTransmission(context: ContextualTransmissionContext): boolean {
  if (!isKnownCantonLaunchSlug(context.eventSlug)) return false;
  if (context.trigger === 'gm_announcement' || context.trigger === 'emergency') return true;

  const subjectKey = subjectKeyFor(context);

  if (context.inlineContent) {
    return !hasViewedTransmission(context.trigger, subjectKey, context.playerId);
  }

  const rule = findMatchingRule(context);
  if (!rule) return false;
  if (rule.onceParPlayer) return !hasViewedTransmission(context.trigger, subjectKey, context.playerId);
  if (rule.cooldownMs) return !hasActiveCooldown(context.trigger, subjectKey, rule.cooldownMs, context.playerId);
  return true;
}

/**
 * The one-call convenience every caller should reach for instead of
 * hand-rolling the shouldShow → resolve → mark → showGameMoment sequence:
 * resolves, checks eligibility, records the view, and queues the
 * GameMoment. Returns whether it actually fired. Client-side only (reads
 * localStorage via transmission-viewed-state.ts and calls
 * GameMomentManager) — server code should call resolveContextualTransmission
 * directly and ship the result to the client instead.
 */
export function showContextualTransmission(context: ContextualTransmissionContext): boolean {
  if (!shouldShowContextualTransmission(context)) return false;
  const transmission = resolveContextualTransmission(context);
  if (!transmission) return false;

  const subjectKey = subjectKeyFor(context);
  markTransmissionViewed(context.trigger, subjectKey, context.playerId);
  showGameMoment({ type: 'commander-transmission', trigger: context.trigger, transmission, viewedStateKey: subjectKey });
  return true;
}
